/* =========================================================
   Helpers
   ========================================================= */

function roundScore(
  value: number
) {
  return (
    Math.round(
      (
        value +
        Number.EPSILON
      ) *
        10000
    ) /
    10000
  );
}

function getChoiceLetter(
  displayedIndex:
    number
) {
  return String.fromCharCode(
    65 +
      displayedIndex
  );
}

function getStatusLabel(
  attempt:
    Attempt,
  labels:
    typeof translations.en
) {
  if (
    attempt.status ===
    "graded"
  ) {
    return labels.graded;
  }

  if (
    attempt.status ===
    "submitted"
  ) {
    return labels.submitted;
  }

  return labels.inProgress;
}

function formatDate(
  value:
    string | null,
  language:
    PdfLanguage
) {
  if (
    !value
  ) {
    return "—";
  }

  const date =
    new Date(
      value
    );

  if (
    Number.isNaN(
      date.getTime()
    )
  ) {
    return "—";
  }

  const locale =
    language ===
    "fr"
      ? "fr-CA"
      : language ===
          "rn"
        ? "rn-BI"
        : "en-CA";

  try {
    return date.toLocaleString(
      locale,
      {
        year:
          "numeric",

        month:
          "short",

        day:
          "2-digit",

        hour:
          "2-digit",

        minute:
          "2-digit",
      }
    );
  } catch {
    return date.toLocaleString(
      "en-CA"
    );
  }
}

/* =========================================================
   Question score
   ========================================================= */

function calculateAutomaticQuestionScore(
  question:
    Question,
  answer:
    AttemptAnswer | undefined
) {
  if (
    question.type ===
    "development"
  ) {
    return 0;
  }

  if (
    question.type ===
    "qcm"
  ) {
    return answer
      ?.selectedChoiceIndex ===
      question.correctChoiceIndex
      ? question.points
      : 0;
  }

  const selected =
    Array.isArray(
      answer
        ?.selectedChoiceIndexes
    )
      ? [
          ...new Set(
            answer
              .selectedChoiceIndexes
          ),
        ]
      : [];

  const correct = [
    ...new Set(
      question
        .correctChoiceIndexes
    ),
  ];

  if (
    correct.length ===
    0 ||
    selected.length ===
    0
  ) {
    return 0;
  }

  const correctSet =
    new Set(
      correct
    );

  let correctlySelected =
    0;

  let incorrectlySelected =
    0;

  for (
    const index of
    selected
  ) {
    if (
      correctSet.has(
        index
      )
    ) {
      correctlySelected +=
        1;
    } else {
      incorrectlySelected +=
        1;
    }
  }

  const pointValue =
    question.points /
    correct.length;

  return roundScore(
    Math.max(
      0,
      Math.min(
        question.points,
        correctlySelected *
          pointValue -
          incorrectlySelected *
            pointValue
      )
    )
  );
}

