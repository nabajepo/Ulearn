export default function AttemptCorrectionPdf({
  quiz,
  attempt,
  questions,
  language = "en",
  expirationArchive = false,
}: AttemptCorrectionPdfProps) {
  const safeLanguage:
    PdfLanguage =
    language === "fr" ||
    language === "rn"
      ? language
      : "en";

  const labels =
    translations[
      safeLanguage
    ];

  /*
   * This special behaviour is allowed only for the
   * automatic archive generated after account expiration.
   *
   * A graded attempt always keeps its normal correction,
   * even when it is included in the expiration archive.
   */
  const isIncompleteExpirationCorrection =
    expirationArchive &&
    attempt.status !==
      "graded";

  /* =====================================================
     Restore frozen question order
     ===================================================== */

  const questionMap =
    new Map(
      questions.map(
        (
          question
        ) => [
          question.id,
          question,
        ]
      )
    );

  const orderedQuestions =
    attempt.questionOrder
      .map(
        (
          questionId
        ) =>
          questionMap.get(
            questionId
          )
      )
      .filter(
        (
          question
        ): question is Question =>
          Boolean(
            question
          )
      );

  /* =====================================================
     Scores
     ===================================================== */

  const automaticScore =
    roundScore(
      orderedQuestions.reduce(
        (
          total,
          question
        ) =>
          total +
          calculateAutomaticQuestionScore(
            question,
            attempt.answers[
              question.id
            ]
          ),
        0
      )
    );

  /*
   * This numeric value remains useful for fully graded
   * attempts.
   *
   * For an incomplete expiration archive we deliberately
   * do NOT use it to manufacture a final score.
   */
  const manualScore =
    roundScore(
      orderedQuestions.reduce(
        (
          total,
          question
        ) => {
          if (
            question.type !==
            "development"
          ) {
            return total;
          }

          return (
            total +
            (
              attempt
                .developmentScores[
                question.id
              ] ??
              0
            )
          );
        },
        0
      )
    );

  /*
   * Normal/manual PDFs preserve the previous behaviour.
   *
   * In an expiration archive, however, an ungraded copy
   * has no legitimate final score because development
   * questions may still require teacher grading.
   */
  const finalScore =
    isIncompleteExpirationCorrection
      ? null
      : attempt.finalScore ??
        roundScore(
          automaticScore +
            manualScore
        );

  const percentage =
    finalScore !== null &&
    quiz.totalPoints > 0
      ? Math.round(
          (
            finalScore /
            quiz.totalPoints
          ) *
            100
        )
      : null;

  /* =====================================================
     PDF
     ===================================================== */

  return (
    <Document
      title={`${labels.documentTitle} - ${quiz.title}`}
      author="ULearn"
      subject={
        labels.documentTitle
      }
      creator="ULearn"
    >
      <Page
        size="A4"
        style={
          styles.page
        }
        wrap
      >
        {/* =================================================
            Header
            ================================================= */}

        <View
          style={
            styles.header
          }
        >
          <View
            style={
              styles.brandRow
            }
          >
            <Text
              style={
                styles.brand
              }
            >
              ULearn
            </Text>

            <Text
              style={
                styles.documentBadge
              }
            >
              {
                labels.correction
              }
            </Text>
          </View>

          <Text
            style={
              styles.title
            }
          >
            {
              labels.documentTitle
            }
          </Text>

          <Text
            style={
              styles.quizTitle
            }
          >
            {labels.quiz}:{" "}
            {quiz.title}
          </Text>
        </View>

        {/* =================================================
            Student
            ================================================= */}

        <View
          style={
            styles.section
          }
        >
          <Text
            style={
              styles.sectionTitle
            }
          >
            {
              labels.student
            }
          </Text>

          <View
            style={
              styles.studentCard
            }
          >
            <Text
              style={
                styles.studentName
              }
            >
              {
                attempt.studentName
              }
            </Text>

            <Text
              style={
                styles.studentEmail
              }
            >
              {labels.email}:{" "}
              {
                attempt.studentEmail
              }
            </Text>

            <View
              style={
                styles.metadataGrid
              }
            >
              <View
                style={
                  styles.metadataItem
                }
              >
                <Text
                  style={
                    styles.metadataLabel
                  }
                >
                  {
                    labels.status
                  }
                </Text>

                <Text
                  style={
                    styles.metadataValue
                  }
                >
                  {getStatusLabel(
                    attempt,
                    labels
                  )}
                </Text>
              </View>

              <View
                style={
                  styles.metadataItem
                }
              >
                <Text
                  style={
                    styles.metadataLabel
                  }
                >
                  {
                    labels.submittedAt
                  }
                </Text>

                <Text
                  style={
                    styles.metadataValue
                  }
                >
                  {formatDate(
                    attempt.submittedAt,
                    safeLanguage
                  )}
                </Text>
              </View>

              <View
                style={
                  styles.metadataItem
                }
              >
                <Text
                  style={
                    styles.metadataLabel
                  }
                >
                  {
                    labels.gradedAt
                  }
                </Text>

                <Text
                  style={
                    styles.metadataValue
                  }
                >
                  {formatDate(
                    attempt.gradedAt,
                    safeLanguage
                  )}
                </Text>
              </View>

              <View
                style={
                  styles.metadataItem
                }
              >
                <Text
                  style={
                    styles.metadataLabel
                  }
                >
                  {
                    labels.quiz
                  }
                </Text>

                <Text
                  style={
                    styles.metadataValue
                  }
                >
                  {
                    quiz.title
                  }
                </Text>
              </View>
            </View>
          </View>
        </View>

        {/* =================================================
            Score summary
            ================================================= */}

        <View
          style={
            styles.section
          }
        >
          <Text
            style={
              styles.sectionTitle
            }
          >
            {
              labels.score
            }
          </Text>

          <View
            style={
              styles.scoreGrid
            }
          >
            <View
              style={
                styles.scoreCard
              }
            >
              <Text
                style={
                  styles.scoreLabel
                }
              >
                {
                  labels.automaticScore
                }
              </Text>

              <Text
                style={
                  styles.scoreValue
                }
              >
                {
                  automaticScore
                }
              </Text>
            </View>

            <View
              style={
                styles.scoreCard
              }
            >
              <Text
                style={
                  styles.scoreLabel
                }
              >
                {
                  labels.manualScore
                }
              </Text>

              <Text
                style={
                  styles.scoreValue
                }
              >
                {isIncompleteExpirationCorrection
                  ? labels.notGraded
                  : manualScore}
              </Text>
            </View>

            <View
              style={
                styles.finalScoreCard
              }
            >
              <Text
                style={
                  styles.finalScoreLabel
                }
              >
                {
                  labels.finalScore
                }
              </Text>

              <Text
                style={
                  styles.finalScoreValue
                }
              >
                {finalScore ===
                null
                  ? labels.notAvailable
                  : `${finalScore} / ${quiz.totalPoints}`}
              </Text>
            </View>

            <View
              style={
                styles.scoreCard
              }
            >
              <Text
                style={
                  styles.scoreLabel
                }
              >
                {
                  labels.percentage
                }
              </Text>

              <Text
                style={
                  styles.scoreValue
                }
              >
                {percentage ===
                null
                  ? labels.notAvailable
                  : `${percentage}%`}
              </Text>
            </View>
          </View>
        </View>

        {/* =================================================
            Questions
            ================================================= */}

        <View>
          <Text
            style={
              styles.sectionTitle
            }
          >
            {
              labels.correction
            }
          </Text>

          {orderedQuestions.map(
            (
              question,
              questionIndex
            ) => {
              const answer =
                attempt.answers[
                  question.id
                ];

              /* ===========================================
                 Development
                 =========================================== */

              if (
                question.type ===
                "development"
              ) {
                const studentAnswer =
                  answer
                    ?.developmentAnswer
                    ?.trim() ||
                  "";

                /*
                 * We distinguish a real teacher score from
                 * an absent score.
                 *
                 * A real score of 0 remains 0.
                 * Missing is NOT converted to 0 in the
                 * expiration archive.
                 */
                const storedScore =
                  attempt
                    .developmentScores[
                    question.id
                  ];

                const hasTeacherScore =
                  typeof storedScore ===
                    "number" &&
                  Number.isFinite(
                    storedScore
                  );

                const score =
                  hasTeacherScore
                    ? storedScore
                    : 0;

                /*
                 * For a non-graded expiration copy, teacher
                 * grading is considered unfinished.
                 *
                 * We therefore display "Not graded" instead
                 * of interpreting a missing score as zero.
                 */
                const showDevelopmentAsNotGraded =
                  isIncompleteExpirationCorrection &&
                  !hasTeacherScore;

                return (
                  <View
                    key={
                      question.id
                    }
                    style={
                      styles.questionCard
                    }
                    wrap={false}
                  >
                    <View
                      style={
                        styles.questionTop
                      }
                    >
                      <View
                        style={
                          styles.questionHeading
                        }
                      >
                        <Text
                          style={
                            styles.questionNumber
                          }
                        >
                          {
                            labels.question
                          }{" "}
                          {
                            questionIndex +
                            1
                          }
                        </Text>

                        <Text
                          style={
                            styles.questionText
                          }
                        >
                          {
                            question.text
                          }
                        </Text>
                      </View>

                      <Text
                        style={
                          styles.pointsBadge
                        }
                      >
                        {showDevelopmentAsNotGraded
                          ? `${labels.notGraded} / ${question.points}`
                          : `${score} / ${question.points}`}
                      </Text>
                    </View>

                    <Text
                      style={
                        styles.typeBadge
                      }
                    >
                      {
                        labels.development
                      }
                    </Text>

                    <Text
                      style={
                        styles.answerTitle
                      }
                    >
                      {
                        labels.studentAnswer
                      }
                    </Text>

                    {studentAnswer ? (
                      <Text
                        style={
                          styles.developmentAnswer
                        }
                      >
                        {
                          studentAnswer
                        }
                      </Text>
                    ) : (
                      <Text
                        style={
                          styles.noAnswer
                        }
                      >
                        {
                          labels.noAnswer
                        }
                      </Text>
                    )}

                    <View
                      style={
                        styles.gradeRow
                      }
                    >
                      <Text
                        style={
                          styles.gradeLabel
                        }
                      >
                        {
                          labels.teacherGrade
                        }
                      </Text>

                      <Text
                        style={
                          styles.gradeValue
                        }
                      >
                        {showDevelopmentAsNotGraded
                          ? `${labels.notGraded} / ${question.points}`
                          : `${score} / ${question.points}`}
                      </Text>
                    </View>
                  </View>
                );
              }

              /* ===========================================
                 QCM / multiple choice
                 =========================================== */

              const selectedIndexes =
                question.type ===
                "qcm"
                  ? typeof answer
                      ?.selectedChoiceIndex ===
                    "number"
                    ? [
                        answer
                          .selectedChoiceIndex,
                      ]
                    : []
                  : Array.isArray(
                        answer
                          ?.selectedChoiceIndexes
                      )
                    ? answer
                        .selectedChoiceIndexes
                    : [];

              const correctIndexes =
                question.type ===
                "qcm"
                  ? [
                      question
                        .correctChoiceIndex,
                    ]
                  : question
                      .correctChoiceIndexes;

              const frozenOrder =
                attempt
                  .choiceOrders[
                  question.id
                ];

              const displayedIndexes =
                Array.isArray(
                  frozenOrder
                ) &&
                frozenOrder.length ===
                  question
                    .choices.length
                  ? frozenOrder
                  : question.choices.map(
                      (
                        _,
                        index
                      ) =>
                        index
                    );

              const automaticQuestionScore =
                calculateAutomaticQuestionScore(
                  question,
                  answer
                );

              return (
                <View
                  key={
                    question.id
                  }
                  style={
                    styles.questionCard
                  }
                  wrap={false}
                >
                  <View
                    style={
                      styles.questionTop
                    }
                  >
                    <View
                      style={
                        styles.questionHeading
                      }
                    >
                      <Text
                        style={
                          styles.questionNumber
                        }
                      >
                        {
                          labels.question
                        }{" "}
                        {
                          questionIndex +
                          1
                        }
                      </Text>

                      <Text
                        style={
                          styles.questionText
                        }
                      >
                        {
                          question.text
                        }
                        </Text>
                      </View>

                    <Text
                      style={
                        styles.pointsBadge
                      }
                    >
                      {
                        automaticQuestionScore
                      }
                      {" / "}
                      {
                        question.points
                      }
                    </Text>
                  </View>

                  <Text
                    style={
                      styles.typeBadge
                    }
                  >
                    {question.type ===
                    "qcm"
                      ? labels.qcm
                      : labels.multipleChoice}
                  </Text>

                  {displayedIndexes.map(
                    (
                      originalIndex,
                      displayedIndex
                    ) => {
                      const selected =
                        selectedIndexes.includes(
                          originalIndex
                        );

                      const correct =
                        correctIndexes.includes(
                          originalIndex
                        );

                      const wrongSelected =
                        selected &&
                        !correct;

                      const choiceStyle =
                        correct
                          ? [
                              styles.choice,
                              styles.correctChoice,
                            ]
                          : wrongSelected
                            ? [
                                styles.choice,
                                styles.wrongSelectedChoice,
                              ]
                            : styles.choice;

                      return (
                        <View
                          key={
                            originalIndex
                          }
                          style={
                            choiceStyle
                          }
                        >
                          <View
                            style={
                              styles.choiceLetter
                            }
                          >
                            <Text>
                              {getChoiceLetter(
                                displayedIndex
                              )}
                            </Text>
                          </View>

                          <Text
                            style={
                              styles.choiceText
                            }
                          >
                            {
                              question
                                .choices[
                                originalIndex
                              ]
                            }
                          </Text>

                          <View
                            style={
                              styles.choiceLabels
                            }
                          >
                            {selected && (
                              <Text
                                style={
                                  styles.selectedLabel
                                }
                              >
                                {
                                  labels.selected
                                }
                              </Text>
                            )}

                            {correct && (
                              <Text
                                style={
                                  styles.correctLabel
                                }
                              >
                                {
                                  labels.correct
                                }
                              </Text>
                            )}

                            {wrongSelected && (
                              <Text
                                style={
                                  styles.wrongLabel
                                }
                              >
                                {
                                  labels.wrong
                                }
                              </Text>
                            )}
                          </View>
                        </View>
                      );
                    }
                  )}

                  {selectedIndexes.length ===
                    0 && (
                    <Text
                      style={
                        styles.noAnswer
                      }
                    >
                      {
                        labels.noAnswer
                      }
                    </Text>
                  )}

                  <View
                    style={
                      styles.gradeRow
                    }
                  >
                    <Text
                      style={
                        styles.gradeLabel
                      }
                    >
                      {
                        labels.automaticGrade
                      }
                    </Text>

                    <Text
                      style={
                        styles.gradeValue
                      }
                    >
                      {
                        automaticQuestionScore
                      }
                      {" / "}
                      {
                        question.points
                      }
                    </Text>
                  </View>
                </View>
              );
            }
          )}
        </View>

        {/* =================================================
            Footer
            ================================================= */}

        <View
          style={
            styles.footer
          }
          fixed
        >
          <Text
            style={
              styles.footerText
            }
          >
            {
              labels.generatedBy
            }
          </Text>

          <Text
            style={
              styles.footerText
            }
            render={({
              pageNumber,
              totalPages,
            }) =>
              `${labels.page} ${pageNumber} ${labels.of} ${totalPages}`
            }
          />
        </View>
      </Page>
    </Document>
  );
}